#!/usr/bin/env bash
# Embed the Cado mascot art (plans/mascot/avocado-v3-*.svg: the four colour
# poses + the menu-bar template glyph) into the app as Swift string literals,
# so `swift run` and the packaged .app load the same art with no SwiftPM
# resource bundle (Brand.Art reads them with NSImage(data:), which renders SVG
# natively on macOS 14+). The SVGs stay the one source of truth; this writes a
# verbatim copy. BrandTests fails until it's re-run after an SVG change.
#
# Usage: bash scripts/embed_mascot_art.sh   (or: make brand)
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ART="$HERE/../plans/mascot"
OUT="$HERE/../Sources/Cado/Brand/MascotArt+SVG.swift"

svg() {   # <swift name> <svg file>
  printf '    static let %s = ##"""\n' "$1"
  cat "$ART/$2"
  printf '\n"""##\n'
}

{
  echo "// Generated by scripts/embed_mascot_art.sh from plans/mascot/avocado-v3-*.svg. Don't edit: re-run it."
  echo ""
  echo "extension Brand.Art {"
  echo "    /// SVG source of each mascot image, keyed by its plans/mascot/avocado-v3-<key>.svg name."
  echo "    static let svgSources: [String: String] = ["
  for key in idle listening thinking done menubar; do
    echo "        \"$key\": ${key}SVG,"
  done
  echo "    ]"
  for key in idle listening thinking done menubar; do
    echo ""
    svg "${key}SVG" "avocado-v3-$key.svg"
  done
  echo "}"
} >"$OUT"
echo "Wrote $OUT" >&2
