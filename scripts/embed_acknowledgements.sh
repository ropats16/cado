#!/usr/bin/env bash
# Embed ACKNOWLEDGEMENTS.md and Cado's LICENSE into the app as Swift string
# literals, for the Acknowledgements screen (#21), so `swift run` and the
# packaged .app show the same text with no SwiftPM resource bundle. The two
# files stay the one source of truth; this writes a verbatim copy.
# AcknowledgementsTests fails until it's re-run after editing either file.
#
# Usage: bash scripts/embed_acknowledgements.sh   (or: make acknowledgements)
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$HERE/.."
OUT="$ROOT/Sources/Cado/Acknowledgements/Acknowledgements+Text.swift"

text() {   # <swift name> <file>
  if grep -q '"""##' "$ROOT/$2"; then
    echo "$2 contains \"\"\"##, which would end the Swift literal" >&2
    rm -f "$OUT.tmp"
    exit 1
  fi
  printf '    static let %s = ##"""\n' "$1"
  cat "$ROOT/$2"
  printf '\n"""##\n'
}

{
  echo "// Generated by scripts/embed_acknowledgements.sh from ACKNOWLEDGEMENTS.md and LICENSE. Don't edit: re-run it."
  echo ""
  echo "extension Acknowledgements {"
  text markdown ACKNOWLEDGEMENTS.md
  echo ""
  text license LICENSE
  echo "}"
} >"$OUT.tmp"   # a refused file must not leave $OUT half-written
mv "$OUT.tmp" "$OUT"
echo "Wrote $OUT" >&2
